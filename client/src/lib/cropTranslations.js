export function translateCrop(cropName, lang) {
  if (!cropName) return cropName;
  if (lang === 'en' || !cropTranslations[lang]) return cropName;
  // Make case insensitive search just in case
  const keys = Object.keys(cropTranslations[lang]);
  const exactKey = keys.find(k => k.toLowerCase() === cropName.toLowerCase());
  return exactKey ? cropTranslations[lang][exactKey] : cropName;
}

export function getEnglishCropName(translatedName, lang) {
  if (!translatedName) return translatedName;
  if (lang === 'en' || !cropTranslations[lang]) return translatedName;
  for (const [enName, trName] of Object.entries(cropTranslations[lang])) {
    if (trName === translatedName || enName === translatedName) return enName;
  }
  return translatedName;
}
